import { describe, it, expect } from 'vitest';
import { isReservedSlug, RESERVED_SLUGS } from '@/lib/constants/reserved-slugs';

/**
 * `LEGACY-203`. Страница `/{lang}/versions/{id}` удалена 15.08.2026, а имя
 * `versions` осталось зарезервированным намеренно: освободить его — значит
 * отдать CMS-странице адрес, по которому раньше играло аудио, вместе со всеми
 * старыми ссылками и закладками.
 *
 * 🔴 Одного комментария в списке для этого мало. `scripts/check-reserved-slugs.mjs`
 * сверяет включение в одну сторону — каталог под `app/[lang]/` обязан быть в
 * списке; лишнее имя без маршрута ему безразлично. Кросс-проверка с копией на
 * бэкенде краснеет только на односторонней правке, а в CI и вовсе пропускается:
 * там рядом нет каталога `../books`. То есть уборка «удалим строку без
 * маршрута» проходит все проверки зелёной — кроме этой.
 */
describe('RESERVED_SLUGS: имена, пережившие свой маршрут (LEGACY-203)', () => {
  it('versions остаётся зарезервированным после удаления страницы плеера', () => {
    expect(isReservedSlug('versions')).toBe(true);
  });

  // Список читается ещё и глазами в ревью, и сверяется с копией на бэкенде
  // построчно, поэтому порядок и отсутствие повторов — часть контракта, а не
  // вкусовщина.
  it('список отсортирован и без повторов', () => {
    const slugs = [...RESERVED_SLUGS];
    expect(slugs).toEqual([...slugs].sort());
    expect(new Set(slugs).size).toBe(slugs.length);
  });
});
