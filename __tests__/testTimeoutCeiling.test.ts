// @vitest-environment node
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { describe, expect, it } from 'vitest';

/**
 * Сторож потолка `testTimeout` (`LEGACY-105`).
 *
 * 🔴 Запись заведена ровно на этот приём: `testTimeout: 40000` — в восемь раз выше
 * умолчания vitest — был следом борьбы с симптомом. Тесты голодали под нагрузкой
 * (на 93 файла `environment 1054 с` и `import 1124 с` при `tests 146 с`), падали
 * по таймауту, и каждый раз порог поднимали. Порог делает голодание реже, но не
 * отличает вытесненный тест от зависшего: красный прогон без единой правки кода
 * читается как «сломали тест», и следующий агент идёт чинить исправный файл.
 *
 * Причину сняли 06.09.2026 — 55 тестов без DOM ушли в окружение `node`, стоимость
 * окружения под `--maxWorkers=4` упала со 168.99 с до 116.36 с. Порог снижен следом,
 * и вот его-то и стережёт этот файл: поднять его обратно — значит снова спрятать
 * голодание, и тогда красное CI перестаёт быть сигналом во второй раз.
 *
 * Проверка текстовая, потому что импортировать конфиг нельзя: `vitest.config.ts`
 * тянет `@vitejs/plugin-react` и ESM-цепочку, а сам файл лежит в `exclude` прогона.
 */
const CONFIG = resolve(__dirname, '..', 'vitest.config.ts');
const raw = readFileSync(CONFIG, 'utf8');

/**
 * 🔴 Комментарии снимаются ДО поиска, и это не косметика. Над самим полем лежит длинный
 * разбор истории значений, и следующий автор, меняя порог, почти наверняка опишет прежнее
 * значение цифрами там же — `// было testTimeout: 40000`. Поиск по всему тексту взял бы
 * число из комментария первым, сравнил его с потолком и пропустил реально поднятый порог
 * зелёным. Сторож, который не может провалиться, хуже отсутствующего: он создаёт
 * уверенность вместо проверки.
 */
const config = raw
  .split('\n')
  .filter((line) => !line.trim().startsWith('//') && !line.trim().startsWith('*'))
  .join('\n');

/**
 * Потолок, а не точное значение: снижать порог можно свободно, это ужесточение.
 * Запрещено только поднимать — ради этого сторож и стоит.
 */
const CEILING_MS = 15000;

describe('порог testTimeout не ползёт вверх', () => {
  it('значение testTimeout вообще находится в конфиге', () => {
    expect(
      config,
      'testTimeout пропал из vitest.config.ts — умолчание vitest 5 с, и набор станет красным целиком'
    ).toMatch(/^\s*testTimeout:\s*\d+/m);
  });

  /**
   * 🔴 Разбор строгий, потому что разрешающая ветка обязана включаться от правды, а не
   * от неудачи разбора (`L-015`). Числовой разделитель TypeScript законен: `testTimeout: 40_000`
   * при наивном `\d+` даёт `'40'`, `Number('40') <= 15000` — сторож зелёный, а прогон снова
   * идёт с сорока секундами. Поэтому разделитель входит в шаблон и снимается перед `Number`,
   * а совпадение обязано быть ровно одно: два поля `testTimeout` в конфиге означают, что
   * разбор больше не знает, какое из них рабочее, и это повод покраснеть, а не выбрать первое.
   */
  it(`testTimeout не выше ${CEILING_MS} мс`, () => {
    const found = [...config.matchAll(/^\s*testTimeout:\s*([\d_]+)/gm)];

    expect(
      found.length,
      'поле testTimeout должно встречаться в конфиге ровно один раз — иначе сторож ' +
        'сравнивает потолок неизвестно с чем'
    ).toBe(1);

    const actual = Number(found[0][1].replace(/_/g, ''));

    expect(actual, 'значение testTimeout не разобралось в число').not.toBeNaN();

    expect(
      actual,
      'порог подняли: голодание тестов снова спрятано, а красный прогон снова ' +
        'неотличим от сломанного теста. Медленный тест чинится причиной — ' +
        'окружением, импортами, — а не порогом (LEGACY-105)'
    ).toBeLessThanOrEqual(CEILING_MS);
  });

  /**
   * Границы решения арбитра 06.09.2026: разделение окружений сделано пофайловым
   * докблоком, а `maxWorkers`/`poolOptions`/`fileParallelism` в конфиг не заводятся.
   * Два зеркальных списка `include`/`exclude` при расхождении уводят тест-файл
   * из прогона вовсе, а невыполненный тест неотличим от зелёного.
   */
  it.each(['maxWorkers', 'poolOptions', 'fileParallelism', 'environmentMatchGlobs'])(
    'в конфиге не заведён %s',
    (key) => {
      expect(config).not.toContain(`${key}:`);
    }
  );
});
