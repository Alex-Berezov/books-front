import type { SupportedLang } from '@/lib/i18n/lang';

export interface EditorialBylineProps {
  lang: SupportedLang;
  /** Текст перед именем редакции, вместе с пробелом: «Описание подготовлено ». */
  prefix?: string;
  /** Имя редакции - ссылка на `/editorial-policy#<anchor>`. */
  teamLabel: string;
  /**
   * Раздел редполитики, на который ведёт имя редакции. Книга и пересказ - `who` («пишут люди»),
   * страница автора - `authors`: её факты собраны из источников, а не написаны людьми
   * (решение арбитра 16.10.2026, `F02 | F02-4`, Р2). Страница анализа - `analysis`: черновик
   * анализа составляет языковая модель (F03 D5, решение арбитра `F03 | F03-3`, В5).
   */
  anchor?: 'who' | 'authors' | 'analysis';
  /** Уже отформатированная подпись даты («Обновлено 13 октября 2026 г.»); без неё даты нет. */
  dateText?: string;
}
