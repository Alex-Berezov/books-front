/**
 * Место в книге, накопленное одной стороной — чтением или прослушиванием.
 *
 * 🔴 Своё время записи у каждой стороны, а не одно на книгу. Слияние решает
 * конфликт по времени, и общая отметка означала бы, что открытая после
 * прослушивания читалка «омолаживает» и аудиопозицию тоже — сервер получил бы
 * её как самую свежую и затёр ею реальную.
 */
export interface LocalProgressSide {
  /**
   * Кто накопил эту сторону: `null` — читатель без аккаунта, иначе его идентификатор.
   *
   * 🔴 Владелец живёт на стороне, а не на записи целиком. Общий компьютер:
   * читатель A с протухшим токеном слушал книгу, потом её же открыл аноним и
   * читал. Будь владелец один на запись, она стала бы «ничьей» вместе с
   * аудиопозицией A — и первое же слияние отправило бы её в чужой аккаунт,
   * обойдя ровно ту защиту, ради которой поле заведено.
   */
  ownerId: string | null;
  /** Номер главы (1..n) в своей нумерации: текстовой или аудио. */
  chapterNumber: number;
  /**
   * Доля 0..1 для текста, секунды для аудио — ровно как требует сервер.
   *
   * 🔴 Единицы разные, и потому позиции разнесены по сторонам. Общее поле
   * означало бы, что секунды прослушивания уезжают на сервер вместе с
   * `chapterNumber`, где допустим только диапазон 0..1, и запрос отвергается.
   */
  position: number;
  /** Время записи, мс epoch. */
  updatedAt: number;
}

/** Какую сторону книги записываем или читаем. */
export type ProgressSideKind = 'text' | 'audio';

/**
 * Локальная запись прогресса — одна на версию книги.
 *
 * 🔴 Текст и аудио лежат раздельно, хотя на сервере это одна строка. Причина в
 * том, что ручка `PUT /me/progress/:versionId` принимает **ровно одно** из полей
 * `chapterNumber` / `audioChapterNumber` (`@Xor` в `UpdateReadingProgressDto`) и
 * трактует `position` по-разному для каждого. Держать их слитно — значит либо
 * слать 400, либо терять одну из сторон.
 */
export interface LocalProgressRecord {
  versionId: string;
  text: LocalProgressSide | null;
  audio: LocalProgressSide | null;
}

/** Куда писать прогресс прямо сейчас. */
export type ProgressTarget = 'server' | 'local' | 'unknown';
