/**
 * Хосты, для которых оптимизатор Next настроен (`next.config.js`, `remotePatterns`).
 *
 * ⚠️ Список нужен не ради экономии, а ради того, чтобы картинка вообще показалась.
 * Оптимизатор на неразрешённом хосте отвечает 400, и она не появляется — а большая
 * часть мест рендера серверные, `onError` в них не поставить. Поэтому: разрешённый
 * хост идёт через оптимизатор, остальные рендерятся `unoptimized`. Заглушка — только
 * когда картинки нет вовсе.
 *
 * ⚠️ Список обязан совпадать со статическими хостами `remotePatterns` в `next.config.js`.
 * Раньше рядом стояло `hostname.endsWith('.com')` — копия шаблона `**.com`, снятого
 * по LEGACY-137. Расхождение молчаливое: предикат отправит в оптимизатор хост, которого
 * в конфиге нет, оптимизатор ответит 400, и картинка не появится. Поэтому список
 * экспортируется: `__tests__/next.config.test.ts` сверяет его со статическими записями
 * конфига в обе стороны — ни добавить хост сюда мимо конфига, ни убрать оттуда мимо
 * этого списка нельзя.
 */
export const OPTIMIZABLE_HTTPS_HOSTS = ['api.bibliaris.com', 'media.bibliaris.com'] as const;

/**
 * Решение «отдавать картинку оптимизатору или нет» — одно на весь сайт.
 *
 * 🔴 LEGACY-278. До 28.08.2026 это решение принималось тринадцатью местами рендера по трём
 * разным правилам: два звали предикат, четыре ставили `unoptimized` безусловно (то есть
 * навсегда отдавали оригинал вместо AVIF/WebP), семь не проверяли ничего — и падали бы
 * четырёхсотой, как только в `coverImageUrl` попадёт хост вне списка. Валидации хоста
 * на бэкенде нет, а `photoUrl` приходит в том числе из импорта JSON, где адрес берётся
 * из вставленного документа как есть.
 *
 * Новый `<Image>` не пишется ни с безусловным `unoptimized`, ни без него — только через
 * этот предикат. Сторож — `__tests__/imageOptimizerPredicate.test.ts`, и он требует этого
 * от **каждого** `<Image>`, без оговорки про источник `src`: сегодня все тринадцать берут
 * `src` из данных API, статических импортов картинок в репозитории нет вовсе, а в `public/`
 * лежат только `favicon.png` и `sitemap.xsl`. Появится первый `<Image>` со статически
 * импортированным `src` (`StaticImageData`, а не строка) — правится сторож вместе с этим
 * абзацем, одной правкой; каст `StaticImageData` к строке ради прохода сторожа даёт
 * `unoptimized` на свой же ассет, то есть ровно ту потерю, ради которой всё это написано.
 */
export const isOptimizableHost = (url: string): boolean => {
  try {
    const { hostname, protocol } = new URL(url);
    if (protocol === 'http:') return hostname === 'localhost';
    return (
      protocol === 'https:' && (OPTIMIZABLE_HTTPS_HOSTS as readonly string[]).includes(hostname)
    );
  } catch {
    // Относительный путь — это наш же домен, он оптимизируется.
    //
    // 🔴 Кроме протокол-относительного: `//host/x.jpg` тоже роняет `new URL` и тоже
    // начинается с косой, но своим доменом не является. Оптимизатор Next отвергает
    // такой адрес отдельной проверкой (`"url" parameter cannot be a protocol-relative
    // URL`) — то есть 400 и пустое место вместо картинки, ровно то, ради чего предикат
    // и написан. Источник не выдуманный: `photoUrl` попадает в базу из импорта JSON
    // как есть, `avatarUrl` вводит пользователь.
    //
    // Проверка типа — не перестраховка: поля приходят из рукописного `types/api-schema`,
    // и `null` мимо него уронил бы `startsWith` наружу, а места рендера в большинстве
    // серверные — упала бы вся страница, а не одна картинка.
    return typeof url === 'string' && url.startsWith('/') && !url.startsWith('//');
  }
};
