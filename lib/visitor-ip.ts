/**
 * Адрес посетителя, который надо переслать в API вместе с серверным запросом.
 *
 * Зачем. Страницы рендерит один контейнер, и вход в аккаунт выполняет он же
 * (NextAuth зовёт `/auth/login` на сервере). Для API все эти запросы приходят
 * с одного адреса — нашего собственного. Без пересылки настоящего адреса лимитер
 * на стороне API считает **весь сайт одним клиентом**: измерено 08.08.2026, шесть
 * попыток входа подряд из контейнера фронта дали 429 на шестой, то есть на весь
 * сайт приходилось пять попыток входа в минуту.
 *
 * API принимает этот заголовок только от источника из `INTERNAL_PROXY_CIDRS`
 * (LEGACY-064), поэтому подставить его снаружи бесполезно.
 */
import { headers } from 'next/headers';

export const VISITOR_IP_HEADER = 'X-Visitor-IP';

/**
 * Возвращает заголовок с адресом посетителя или пустой объект.
 *
 * Пустой объект — нормальный исход, а не ошибка: код вызывается и вне запроса
 * (генерация статики, прогрев кеша, клиентские вызовы), и там посетителя просто
 * нет. `headers()` в таком контексте бросает, поэтому вызов обёрнут.
 */
export const visitorIpHeader = (): Record<string, string> => {
  try {
    const incoming = headers();
    // Cloudflare ставит `cf-connecting-ip` и переписывает его сам, поэтому
    // подделать его посетитель не может. `x-forwarded-for` — запасной путь на
    // случай, если сайт когда-нибудь окажется без CF; берётся первый адрес слева,
    // потому что справа дописывают прокси.
    const cf = incoming.get('cf-connecting-ip');
    const forwarded = incoming.get('x-forwarded-for')?.split(',')[0]?.trim();
    const ip = cf?.trim() || forwarded;

    return ip ? { [VISITOR_IP_HEADER]: ip } : {};
  } catch {
    return {};
  }
};
