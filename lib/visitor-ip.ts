/**
 * Адрес посетителя, который надо переслать в API вместе с серверным запросом.
 *
 * Зачем. Вход в аккаунт выполняет сервер: NextAuth зовёт `/auth/login` из
 * колбэка `authorize`. Для API все входы сайта приходят с одного адреса — нашего
 * собственного, — и лимитер считает **весь сайт одним клиентом**: измерено
 * 08.08.2026, шестая попытка входа подряд уже 429, то есть пять попыток в минуту
 * на всех посетителей.
 *
 * 🔴 **Здесь намеренно нет `next/headers`.** Первая версия читала заголовки
 * оттуда, и сборка упала: `lib/http.ts` импортируется в том числе клиентскими
 * компонентами (`RegisterClient`), а `next/headers` в клиентский бандл не
 * попадает — это запрет времени сборки, `try/catch` его не обходит. Поэтому
 * адрес берётся из объекта запроса, который передаёт сам фреймворк.
 *
 * API принимает этот заголовок только от источника из `INTERNAL_PROXY_CIDRS`
 * (LEGACY-064), поэтому подставить его снаружи бесполезно.
 */

export const VISITOR_IP_HEADER = 'X-Visitor-IP';

interface HeaderCarrier {
  headers: { get: (name: string) => string | null };
}

/**
 * Заголовок с адресом посетителя или пустой объект.
 *
 * Пустой объект — нормальный исход: запрос может выполняться вне пользовательского
 * контекста (прогрев, плановая задача). Тогда лимитер посчитает по адресу фронта —
 * грубее, но это не отказ.
 */
export const visitorIpHeaderFrom = (request?: HeaderCarrier | null): Record<string, string> => {
  if (!request) return {};

  try {
    // Cloudflare ставит `cf-connecting-ip` сам и переписывает присланное клиентом,
    // поэтому подделать его посетитель не может. `x-forwarded-for` — запасной путь
    // на случай работы без CF; берётся первый адрес слева, справа дописывают прокси.
    const cf = request.headers.get('cf-connecting-ip')?.trim();
    const forwarded = request.headers.get('x-forwarded-for')?.split(',')[0]?.trim();
    const ip = cf || forwarded;

    return ip ? { [VISITOR_IP_HEADER]: ip } : {};
  } catch {
    return {};
  }
};
