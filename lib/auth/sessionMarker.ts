/**
 * Клиентская отметка «сессия, скорее всего, есть».
 *
 * Куку сессии NextAuth (`__Secure-authjs.session-token`) браузерный код прочитать
 * не может — она `HttpOnly`. Поэтому `AppProviders` смотрит на эту отметку, чтобы
 * анонимному посетителю не делать лишний запрос к `/api/auth/session` на каждой
 * загрузке страницы.
 *
 * 🔴 Отметка — подсказка, и цена у её ошибок разная:
 *
 * - **ложноположительная** (отметка есть, сессии нет) стоит один запрос: провайдер
 *   получает «состояние неизвестно», спрашивает сервер и узнаёт правду;
 * - **ложноотрицательная** (сессия есть, отметки нет) стоит интерфейса: провайдер
 *   получает «точно не залогинен» и **не спрашивает сервер вовсе** до следующего
 *   планового опроса — 15 минут с кнопкой «Sign In» у вошедшего пользователя.
 *
 * Ровно это и случилось 08.08.2026: отметку ставила только парольная форма, а вход
 * через Google идёт мимо неё — NextAuth сам уводит браузер на `/api/auth/callback/...`
 * и возвращает уже на `callbackUrl`, так что клиентский код формы не выполняется.
 * Сессия создавалась исправно, врал только интерфейс.
 *
 * Поэтому отметку ставит и снимает **только** этот модуль, а не строки куки,
 * разбросанные по компонентам: путь входа, забывший её поставить, — это не
 * забытая строка, а сломанный вход с точки зрения пользователя.
 */

const MARKER_NAME = 'logged_in';
const MARKER_MAX_AGE_SECONDS = 31_536_000; // 1 год

/**
 * Поставить отметку. Для OAuth вызывается **до** ухода на провайдера: вернётся
 * пользователь уже на другую страницу, и поставить её будет негде. Если вход не
 * состоится, отметка окажется ложноположительной — это дешёвая ошибка (см. выше).
 */
export const markLoggedIn = (): void => {
  if (typeof document === 'undefined') return;
  document.cookie = `${MARKER_NAME}=true; path=/; max-age=${MARKER_MAX_AGE_SECONDS}; SameSite=Lax`;
};

/** Снять отметку. Вызывается на каждом выходе, включая принудительный по 401. */
export const clearLoggedInMarker = (): void => {
  if (typeof document === 'undefined') return;
  document.cookie = `${MARKER_NAME}=; path=/; expires=Thu, 01 Jan 1970 00:00:00 GMT; SameSite=Lax`;
};

/** Есть ли отметка. На сервере всегда `false` — куки читаются из `document`. */
export const hasLoggedInMarker = (): boolean => {
  if (typeof document === 'undefined') return false;
  return document.cookie.split(';').some((item) => item.trim().startsWith(`${MARKER_NAME}=`));
};
