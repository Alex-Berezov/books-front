'use client';

import { useSession } from 'next-auth/react';

/**
 * Можно ли сохранять прогресс чтения или прослушивания.
 *
 * Чтение и прослушивание открыты анониму (решение владельца от 22.08.2026), а
 * `PUT /me/progress/:versionId` идёт через `httpPutAuth` с `requireAuth: true`.
 * Без проверки читалка и плеер били бы в него у каждого посетителя.
 *
 * 🔴 Проверять наличие пользователя в сессии **недостаточно**. При неудачном
 * обновлении токена `refreshAccessToken` возвращает прежний, протухший
 * `accessToken` и ставит `session.error` (`lib/auth/config.ts`), а `session.user`
 * остаётся на месте. Запрос тогда уходит, получает 401, `withAuthRetry`
 * повторяет его с тем же токеном и на второй неудаче зовёт `handleAuthFailure`
 * с `signOut({ redirect: true })`. Читателя выбрасывало бы на форму входа
 * посреди книги — со страницы, которая входа больше не требует. Триггеры
 * бытовые: ротация refresh-токена во второй вкладке, выход на другом
 * устройстве, отказ сети на `/auth/refresh`.
 *
 * Признак один на читалку и плеер намеренно: два разных условия в двух файлах
 * означают, что следующая правка почини́т один и пропустит второй.
 *
 * Цена выбранного признака: пока `status === 'loading'`, прогресс не пишется.
 * Окно — доли секунды до ответа `/api/auth/session`, и оно кончается раньше,
 * чем читалка успевает сменить главу (сохранение отложено на 3 секунды).
 */
export const useCanSaveProgress = (): boolean => {
  const { data: session, status } = useSession();

  return status === 'authenticated' && !session?.error;
};
