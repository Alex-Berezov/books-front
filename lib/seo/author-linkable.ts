/**
 * Достоин ли автор внутренней ссылки, места в карте сайта и индексации.
 *
 * Авторы были единственным публичным типом страниц, целиком выпавшим из контура
 * «ссылка = sitemap = robots», выстроенного по таксономиям: в
 * `sitemap-authors-en.xml` лежали все 10 из 10, а страница автора без единой
 * опубликованной книги отдавала `index, follow` наравне с наполненной.
 *
 * Правило вынесено сюда, а не оставлено выражением внутри маршрута, ровно
 * потому, что решать по нему должны **оба** сигнала. Дефект задачи в том и
 * состоял, что сигналы расходились: список авторов говорил «0 книг», а страница
 * показывала книгу.
 *
 * ⚠️ Неизвестность — не ноль. `booksCount`, которого нет в ответе, означает, что
 * выяснить не удалось, и автор остаётся видимым: `200 + noindex` Google
 * исполняет и возвращает страницу неделями, а лишний URL в карте сайта на время
 * сбоя не стоит ничего. Та же асимметрия, что в `buildRobotsByCount`.
 */
export type AuthorLinkability = {
  booksCount?: number | null;
};

export function isAuthorLinkable(author: AuthorLinkability): boolean {
  if (typeof author.booksCount !== 'number') return true;
  return author.booksCount > 0;
}
