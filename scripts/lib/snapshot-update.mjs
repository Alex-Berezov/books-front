/**
 * Общее решение «переписывать ли снимок» для всех гейтов со снимком.
 *
 * Живёт отдельным модулем, потому что дверь обновления должна быть одна: пока
 * условие было выписано в каждом гейте своими руками, ужесточение в одном месте
 * оставляло второй гейт с прежней дверью (класс `LEGACY-295`).
 *
 * Снимок переписывается только по явному флагу и только вне CI: ожидание,
 * переписанное конвейером под изменившийся код, проверкой быть перестаёт.
 */
export const shouldAcceptUpdate = (updateRequested, inCi) => updateRequested && !inCi;
